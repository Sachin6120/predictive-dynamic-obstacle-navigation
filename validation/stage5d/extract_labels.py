#!/usr/bin/env python3
"""Flatten the retained Stage-5B recordings into the Stage-5D replay table.

The table is the input the C++ audit consumes.

WHY A SEPARATE STEP. The three comparison arms of Stage-5D section 10 need
REAL classifier output, not a simulated classifier: arm B must use the labels
and confidences the shipped Stage-5B pipeline actually produced, and arm C must
use the ground-truth class the actor actually was. Both already exist, per
scan, in validation/stage5b/raw/*.jsonl.gz (2,547 rows, 57 tracks). This script
does nothing but reshape them -- no filtering by outcome, no smoothing, no
relabelling -- so that every selection and every reachability number in the
audit is computed by the PRODUCTION headers rather than re-implemented in
Python.

The emitted columns are exactly what the selector and the Kalman filter need:

    scenario_idx track_idx stamp x y speed observations kalman_init
    runtime_label runtime_conf gt_label

Labels are emitted as the wire ObstacleClass values (0 UNKNOWN, 1 PEDESTRIAN,
2 BIKE, 3 VEHICLE) so the C++ side casts rather than parses.

GROUND TRUTH NEVER REACHES A RUNTIME PATH. `gt_label` is column 11 and is read
ONLY by the audit's oracle arm, which is labelled ANALYTICAL / EVALUATION ONLY
everywhere it appears. The production node does not read this file, is not
built against it, and has no parameter that could.

    validation/stage5d/extract_labels.py --out <dir>/replay.txt
"""
import argparse
import gzip
import json
import os
from collections import defaultdict

#: Must match ObstacleClass in obstacle_classification.hpp and the CLASS_*
#: constants in TrackedObject.msg. Checked against the recordings below.
CLASS_VALUE = {'UNKNOWN': 0, 'PEDESTRIAN': 1, 'BIKE': 2, 'VEHICLE': 3}

RAW_DIR = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', 'stage5b', 'raw')


def load_rows():
    """Every recorded row from a scenario that actually ran, as dicts."""
    rows = []
    for name in sorted(os.listdir(RAW_DIR)):
        if not name.endswith('.jsonl.gz'):
            continue
        with gzip.open(os.path.join(RAW_DIR, name), 'rt') as handle:
            for line in handle:
                row = json.loads(line)
                if row.get('scenario_ok'):
                    rows.append(row)
    return rows


def main():
    """Write the replay table."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, help='output table path')
    args = parser.parse_args()

    rows = load_rows()
    # One record per (scenario, track id), time ordered, because the audit
    # re-runs the production Kalman filter along each track and that is only
    # meaningful in order.
    tracks = defaultdict(list)
    for row in rows:
        tracks[(row['scenario'], row['track_id'])].append(row)
    for key in tracks:
        tracks[key].sort(key=lambda r: r['stamp'])

    scenarios = sorted({k[0] for k in tracks})
    scenario_idx = {s: i for i, s in enumerate(scenarios)}

    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    n = 0
    with open(args.out, 'w') as handle:
        handle.write(
            '# Stage-5D replay table, generated by validation/stage5d/extract_labels.py\n'
            '# from validation/stage5b/raw/. Columns:\n'
            '# scenario_idx track_idx stamp x y speed observations kalman_init '
            'runtime_label runtime_conf gt_label\n')
        for t_idx, key in enumerate(sorted(tracks)):
            scenario, _ = key
            for row in tracks[key]:
                handle.write(
                    '%d %d %.6f %.9f %.9f %.9f %d %d %d %.9f %d\n' % (
                        scenario_idx[scenario], t_idx, row['stamp'],
                        row['x'], row['y'], row['speed'],
                        int(row['observations']),
                        1 if row['kalman_initialized'] else 0,
                        CLASS_VALUE[row['pred_class']], row['pred_conf'],
                        CLASS_VALUE[row['gt_class']]))
                n += 1

    print('%s: %d rows, %d tracks, %d scenarios' % (
        args.out, n, len(tracks), len(scenarios)))


if __name__ == '__main__':
    main()
